import { SOURCE_IDS, activeSourceIds } from "./registry";

export function papersearchPrompt(): string {
  const sourceList = activeSourceIds().join(", ");
  return [
    "The papersearch plugin (papersearch_* tools) is the UPSTREAM of the OKF library: it searches open academic",
    "sources and stages PDFs into the OKF sources dir. The full pipeline in one conversation:",
    "  papersearch_search / papersearch_fetch  →  okf_ingest  →  okf_search / okf_graph / okf_coverage",
    "",
    "=== TOOLS ===",
    "  papersearch_search: multi-source search, returns deduplicated paper cards (title, authors, year, DOI,",
    "    pdf_url, abstract digest). Parameters: query (required), sources (comma-separated, default the active set),",
    "    maxResults (per source, default 5), year (Semantic Scholar filter like '2022' or '2020-2023').",
    "  papersearch_fetch: one-call loop — search, then download the top N papers with a working PDF source",
    "    into the OKF sources dir. Defaults to a background job: returns a job id, per-paper progress lands",
    "    in the job output, and the completion detail lists the staged file names — job_output with",
    "    wait=true timeout_ms=600000 when blocked; job_kill cancels. background=false runs synchronously and",
    "    returns the manifest. Parameters: query, sources, maxResults, year, count (default 3, max 10),",
    "    background (default true).",
    "  papersearch_download: download one known paper by source + paper_id (e.g. arxiv + 2404.18021v2).",
    "  papersearch_download_scihub: LAST-RESORT download by DOI / title / PMID / URL straight from a Sci-Hub",
    "    mirror when the OA fallback chain fails (hosts paywalled papers — use sparingly).",
    "  papersearch_sources: list available source connectors.",
    "  papersearch_help: this guide.",
    "",
    `=== SOURCES (${activeSourceIds().length} active / ${SOURCE_IDS.length} registered) ===`,
    `  ${sourceList}`,
    "  PDF capable: arxiv, biorxiv, medrxiv, iacr, semantic (OA), pmc (OA), core, zenodo, hal.",
    "  Metadata-only (papers still enter the fetch pool via pdf_url/DOI + the fallback chain): pubmed, crossref,",
    "    openalex, europepmc, openaire, dblp, citeseerx, doaj, base, ssrn, google_scholar.",
    "  Key-gated: ieee (Xplore metadata API, needs PAPERSEARCH_IEEE_API_KEY), acm (no open metadata API — errors",
    "    with guidance even when a key is stored; use crossref/semantic/openalex for ACM content).",
    "  Fragile (bot detection / rate limits — expect per-source errors in the errors map): google_scholar,",
    "    citeseerx, base (needs institutional IP), ssrn. google_scholar accepts a forward proxy",
    "    (PAPERSEARCH_GOOGLE_SCHOLAR_PROXY_URL, http:// or socks5://) to route around IP blocks.",
    "  biorxiv/medrxiv searches treat the query as a CATEGORY name (API has no keyword search):",
    "    'cell biology', 'genomics', 'neuroscience' — not full sentences.",
    "  For broad discovery prefer sources='arxiv,pubmed,semantic,crossref,openalex'; add europepmc/pmc for",
    "  biomedical. 'all' includes fragile and category-based sources — use it when the user asks for it.",
    "",
    "=== DOWNLOAD FALLBACK CHAIN ===",
    "  When a source cannot serve the PDF itself, papersearch_download/papersearch_fetch try, in order:",
    "  1. the source's native PDF link (when it has one),",
    "  2. the pdf_url from the search card,",
    "  3. open repositories searched by DOI then title (openaire → core → europepmc → pmc),",
    "  4. the unpaywall OA resolver (needs PAPERSEARCH_UNPAYWALL_EMAIL / PAPERSEARCH_CONTACT_EMAIL),",
    "  5. the Sci-Hub mirror list, auto-rotated (on by default; disable with",
    "     PAPERSEARCH_USE_SCI_HUB=false, mirrors via PAPERSEARCH_SCI_HUB_BASE_URL as a",
    "     comma-separated list — hosts paywalled papers, so treat as last resort).",
    "  Every candidate is validated as a real PDF (%PDF- magic) before it is kept.",
    "",
    "=== CLOSED LOOP WITH OKF ===",
    "  After papersearch_fetch / papersearch_download returns downloaded paths (for a background fetch,",
    "  read them from the job output / completion detail):",
    "  1. okf_ingest with those paths (the download dir is OKF/sources/pdfs, so bare filenames work).",
    "  2. okf_stats / okf_search to verify the new papers compiled into concepts and claims.",
    "  Do not re-download papers already in OKF/sources/pdfs — the download tool marks them 'exists'",
    "  (sidecar sha256 verified); changed files are overwritten and marked 'replaced'.",
    "",
    "=== SEARCH QUALITY ===",
    "  Call MULTIPLE searches with varied phrasings before concluding coverage; check the errors map for",
    "  sources that failed and re-query on a different source instead of reporting a gap as fact.",
    "  Cite only DOIs/ids returned by the tools. Do not invent paper ids or DOIs.",
  ].join("\n");
}

